export const common = { en, ar };
export type CommonDict = typeof en;

export function getCommon(locale: Locale): CommonDict {
  return common[locale];
}

/** Translate an RPC/Postgres error message into something human. */
export function errorText(locale: Locale, code: string | null | undefined): string {
  const t = common[locale].errors;
  return (code && t[code]) || t.generic!;
}

/** Comma-separated unpublished_reason → readable list. */
export function blockerTexts(
  locale: Locale,
  codes: string[] | string | null | undefined,
): string[] {
  const list = Array.isArray(codes) ? codes : (codes ?? "").split(",").filter(Boolean);
  const t = common[locale].blockers;
  return list.map((c) => t[c] ?? c);
}
